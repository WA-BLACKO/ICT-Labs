/* =========================================================
   ICT LAB — LIQUID CURSOR
   BIG GLOW + SMALL FOLLOWERS
   ========================================================= */

const cursorGlow =
    document.getElementById(
        "cursorGlow"
    );


const trailElements =
    Array.from(
        document.querySelectorAll(
            ".cursor-trail"
        )
    );



/* =========================================================
   CURSOR POSITIONS
   ========================================================= */

let mouseX = 0;
let mouseY = 0;


let glowX = 0;
let glowY = 0;


let cursorStarted = false;



/* =========================================================
   CREATE TRAIL STATE
   ========================================================= */

const trailBubbles =
    trailElements.map(
        (element) => ({

            element: element,

            x: 0,

            y: 0

        })
    );



/* =========================================================
   MOUSE MOVEMENT
   ========================================================= */

document.addEventListener(
    "mousemove",
    (event) => {


        mouseX =
            event.clientX;


        mouseY =
            event.clientY;



        /*
           FIRST MOVEMENT
        */

        if (!cursorStarted) {


            glowX =
                mouseX;


            glowY =
                mouseY;


            trailBubbles.forEach(
                (bubble) => {

                    bubble.x =
                        mouseX;

                    bubble.y =
                        mouseY;

                }
            );


            cursorStarted =
                true;


            animateLiquidCursor();

        }



        /*
           SHOW LARGE GLOW
        */

        if (cursorGlow) {

            cursorGlow.style.opacity =
                "1";

        }



        /*
           SHOW SMALL BUBBLES
        */

        trailBubbles.forEach(
            (bubble, index) => {


                bubble.element.style.opacity =
                    Math.max(

                        0.18,

                        0.78 -
                        index * 0.10

                    );

            }
        );

    }
);



/* =========================================================
   CURSOR ANIMATION
   ========================================================= */

function animateLiquidCursor() {

    if (!cursorStarted) {

        return;

    }



    /* =====================================================
       LARGE LIQUID GLOW
       ===================================================== */

    glowX +=
        (
            mouseX -
            glowX
        ) *
        0.14;


    glowY +=
        (
            mouseY -
            glowY
        ) *
        0.14;



    if (cursorGlow) {

        cursorGlow.style.left =
            glowX + "px";


        cursorGlow.style.top =
            glowY + "px";

    }



    /* =====================================================
       SMALL FOLLOWER CHAIN
       ===================================================== */

    let targetX =
        glowX;


    let targetY =
        glowY;


    const time =
        performance.now();



    trailBubbles.forEach(
        (bubble, index) => {


            /*
               First follower is faster.

               Each following bubble becomes
               slightly slower.
            */

            const speed =
                Math.max(

                    0.075,

                    0.22 -
                    index * 0.025

                );



            bubble.x +=
                (
                    targetX -
                    bubble.x
                ) *
                speed;


            bubble.y +=
                (
                    targetY -
                    bubble.y
                ) *
                speed;



            /*
               SMALL LIQUID MOVEMENT
            */

            const waveX =
                Math.sin(

                    time * 0.004 +

                    index * 1.5

                ) *

                index *

                0.7;



            const waveY =
                Math.cos(

                    time * 0.003 +

                    index * 1.3

                ) *

                index *

                0.35;



            /*
               POSITION BUBBLE
            */

            bubble.element.style.left =
                (
                    bubble.x +
                    waveX
                ) +
                "px";


            bubble.element.style.top =
                (
                    bubble.y +
                    waveY
                ) +
                "px";



            /*
               NEXT BUBBLE FOLLOWS
               THE PREVIOUS BUBBLE
            */

            targetX =
                bubble.x;


            targetY =
                bubble.y;

        }
    );



    requestAnimationFrame(
        animateLiquidCursor
    );

}



/* =========================================================
   MOUSE LEAVES PAGE
   ========================================================= */

document.addEventListener(
    "mouseleave",
    () => {


        if (cursorGlow) {

            cursorGlow.style.opacity =
                "0";

        }


        trailBubbles.forEach(
            (bubble) => {

                bubble.element.style.opacity =
                    "0";

            }
        );

    }
);



