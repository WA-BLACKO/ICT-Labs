/* =========================================================
   CURRENT COURSE STATE — SINGLE + MULTI-PART EPISODES
   ========================================================= */

let currentCourse = null;
let currentEpisode = 0;
let currentPart = null;
const expandedEpisodes = new Set();

function goHome() {
    window.location.href = "index.html";
}

function getDriveFileId(link) {
    if (!link) return null;

    let match = link.match(/\/file\/d\/([a-zA-Z0-9_-]+)/);
    if (match) return match[1];

    match = link.match(/[?&]id=([a-zA-Z0-9_-]+)/);
    return match ? match[1] : null;
}

/* Build the true Previous/Next order, including every part. */
function getPlayableItems() {
    if (!currentCourse || !courses[currentCourse]) return [];

    const items = [];

    courses[currentCourse].episodes.forEach((episode, episodeIndex) => {
        if (Array.isArray(episode.parts) && episode.parts.length) {
            episode.parts.forEach((part, partIndex) => {
                items.push({
                    episodeIndex,
                    partIndex,
                    driveLink: part.driveLink
                });
            });
        } else {
            items.push({
                episodeIndex,
                partIndex: null,
                driveLink: episode.driveLink
            });
        }
    });

    return items;
}

function getCurrentPlayableIndex() {
    return getPlayableItems().findIndex(item =>
        item.episodeIndex === currentEpisode &&
        item.partIndex === currentPart
    );
}

function completionId(episodeIndex, partIndex = null) {
    return partIndex === null
        ? `e:${episodeIndex}`
        : `e:${episodeIndex}:p:${partIndex}`;
}

function openCourse(courseId) {
    if (!courses[courseId]) {
        console.error("Course does not exist:", courseId);
        return;
    }

    currentCourse = courseId;
    currentEpisode = 0;
    currentPart = null;
    expandedEpisodes.clear();

    const courseSelection = document.getElementById("courseSelection");
    const coursePlayer = document.getElementById("coursePlayer");
    const courseTitle = document.getElementById("courseTitle");
    const courseDescription = document.getElementById("courseDescription");
    const episodeSearch = document.getElementById("episodeSearch");
    const course = courses[courseId];

    if (courseSelection) courseSelection.classList.add("hidden");
    if (coursePlayer) coursePlayer.classList.remove("hidden");
    if (courseTitle) courseTitle.textContent = course.title;
    if (courseDescription) courseDescription.textContent = course.description;
    if (episodeSearch) episodeSearch.value = "";

    const first = course.episodes[0];

    if (first && Array.isArray(first.parts) && first.parts.length) {
        expandedEpisodes.add(0);
        loadPart(0, 0);
    } else {
        loadEpisode(0);
    }

    updateProgress();
    window.scrollTo({ top: 0, behavior: "smooth" });
}

function showCourses() {
    const coursePlayer = document.getElementById("coursePlayer");
    const courseSelection = document.getElementById("courseSelection");
    const courseVideo = document.getElementById("courseVideo");

    if (coursePlayer) coursePlayer.classList.add("hidden");
    if (courseSelection) courseSelection.classList.remove("hidden");
    if (courseVideo) courseVideo.src = "";

    currentCourse = null;
    currentEpisode = 0;
    currentPart = null;
    expandedEpisodes.clear();

    window.scrollTo({ top: 0, behavior: "smooth" });
}

/* Normal episode. If it has parts, start Part 01 instead. */
function loadEpisode(index) {
    if (!currentCourse) return;

    const course = courses[currentCourse];
    if (!course || index < 0 || index >= course.episodes.length) return;

    const episode = course.episodes[index];

    if (Array.isArray(episode.parts) && episode.parts.length) {
        expandedEpisodes.add(index);
        loadPart(index, 0);
        return;
    }

    currentEpisode = index;
    currentPart = null;

    loadVideoIntoPlayer(
        episode.driveLink,
        episode.title,
        null
    );
}

/* Load one sub-part of a multi-part episode. */
function loadPart(episodeIndex, partIndex) {
    if (!currentCourse) return;

    const episode = courses[currentCourse]?.episodes?.[episodeIndex];

    if (!episode || !Array.isArray(episode.parts)) return;
    if (partIndex < 0 || partIndex >= episode.parts.length) return;

    const part = episode.parts[partIndex];

    currentEpisode = episodeIndex;
    currentPart = partIndex;
    expandedEpisodes.add(episodeIndex);

    loadVideoIntoPlayer(
        part.driveLink,
        episode.title,
        part
    );
}

function loadVideoIntoPlayer(driveLink, episodeTitleText, part = null) {
    const episodeNumber = document.getElementById("episodeNumber");
    const episodeTitle = document.getElementById("episodeTitle");
    const courseVideo = document.getElementById("courseVideo");

    if (episodeNumber) {
        episodeNumber.textContent = part
            ? `${episodeTitleText.toUpperCase()} • ${part.title.toUpperCase()}`
            : episodeTitleText.toUpperCase();
    }

    if (episodeTitle) {
        episodeTitle.textContent = part
            ? `${episodeTitleText} — ${part.title}`
            : episodeTitleText;
    }

    const driveId = getDriveFileId(driveLink);

    if (courseVideo) {
        if (driveId) {
            courseVideo.src =
                `https://drive.google.com/file/d/${driveId}/preview`;
        } else {
            courseVideo.src = "";
            console.warn("No valid Google Drive link:", driveLink);
        }
    }

    updateNavigationButtons();
    updateCompleteButton();
    renderEpisodes();
}

/* Previous/Next now walks through parts too. */
function nextEpisode() {
    const items = getPlayableItems();
    const position = getCurrentPlayableIndex();

    if (position >= 0 && position < items.length - 1) {
        playItem(items[position + 1]);
    }
}

function previousEpisode() {
    const items = getPlayableItems();
    const position = getCurrentPlayableIndex();

    if (position > 0) {
        playItem(items[position - 1]);
    }
}

function playItem(item) {
    if (!item) return;

    if (item.partIndex === null) {
        loadEpisode(item.episodeIndex);
    } else {
        loadPart(item.episodeIndex, item.partIndex);
    }
}

function updateNavigationButtons() {
    const previousBtn = document.getElementById("previousBtn");
    const nextBtn = document.getElementById("nextBtn");
    const items = getPlayableItems();
    const position = getCurrentPlayableIndex();

    if (previousBtn) previousBtn.disabled = position <= 0;

    if (nextBtn) {
        nextBtn.disabled =
            position < 0 || position >= items.length - 1;
    }
}

/* =========================================================
   COMPLETION + LOCAL STORAGE
   ========================================================= */

function storageKey() {
    return "ictlab-course-" + currentCourse;
}

function getCompleted() {
    if (!currentCourse) return [];

    try {
        const saved = localStorage.getItem(storageKey());
        if (!saved) return [];

        const parsed = JSON.parse(saved);
        if (!Array.isArray(parsed)) return [];

        /* Migrate old numeric completion values automatically. */
        return parsed.map(value =>
            typeof value === "number" ? `e:${value}` : value
        );
    } catch (error) {
        console.warn("Could not read course progress.", error);
        return [];
    }
}

function saveCompleted(completed) {
    if (!currentCourse) return;

    try {
        localStorage.setItem(
            storageKey(),
            JSON.stringify([...new Set(completed)])
        );
    } catch (error) {
        console.warn("Could not save course progress.", error);
    }
}

function toggleComplete() {
    if (!currentCourse) return;

    let completed = getCompleted();
    const id = completionId(currentEpisode, currentPart);

    if (completed.includes(id)) {
        completed = completed.filter(item => item !== id);
    } else {
        completed.push(id);
    }

    saveCompleted(completed);
    updateCompleteButton();
    updateProgress();
    renderEpisodes();
}

function updateCompleteButton() {
    if (!currentCourse) return;

    const completeBtn = document.getElementById("completeBtn");
    if (!completeBtn) return;

    const completed = getCompleted();
    const id = completionId(currentEpisode, currentPart);
    const done = completed.includes(id);

    completeBtn.textContent =
        done ? "✓ Completed" : "✓ Mark Completed";

    completeBtn.classList.toggle("completed", done);
}

function isEpisodeCompleted(episodeIndex) {
    if (!currentCourse) return false;

    const episode = courses[currentCourse].episodes[episodeIndex];
    const completed = getCompleted();

    if (Array.isArray(episode.parts) && episode.parts.length) {
        return episode.parts.every((part, partIndex) =>
            completed.includes(completionId(episodeIndex, partIndex))
        );
    }

    return completed.includes(completionId(episodeIndex));
}

function updateProgress() {
    if (!currentCourse) return;

    const items = getPlayableItems();
    const completed = getCompleted();

    const completedCount = items.filter(item =>
        completed.includes(
            completionId(item.episodeIndex, item.partIndex)
        )
    ).length;

    const total = items.length;
    const percentage = total ? (completedCount / total) * 100 : 0;

    const progressText = document.getElementById("progressText");
    const progressBar = document.getElementById("progressBar");

    if (progressText) {
        progressText.textContent = `${completedCount} / ${total}`;
    }

    if (progressBar) {
        progressBar.style.width = `${percentage}%`;
    }
}

/* =========================================================
   EPISODE MENU — NOW RENDERS SUB-PARTS
   ========================================================= */

function renderEpisodes() {
    if (!currentCourse) return;

    const episodeList = document.getElementById("episodeList");
    if (!episodeList) return;

    const episodeSearch = document.getElementById("episodeSearch");
    const search = episodeSearch
        ? episodeSearch.value.toLowerCase().trim()
        : "";

    const course = courses[currentCourse];
    const completed = getCompleted();

    episodeList.innerHTML = "";

    course.episodes.forEach((episode, index) => {
        const hasParts =
            Array.isArray(episode.parts) && episode.parts.length > 0;

        const episodeMatches =
            episode.title.toLowerCase().includes(search);

        const matchingParts = hasParts
            ? episode.parts.filter(part =>
                part.title.toLowerCase().includes(search)
            )
            : [];

        if (search && !episodeMatches && matchingParts.length === 0) {
            return;
        }

        const group = document.createElement("div");
        group.className = "episode-group";

        const button = document.createElement("button");
        button.type = "button";
        button.className = "episode";

        if (index === currentEpisode) {
            button.classList.add("active");
        }

        const number = document.createElement("span");
        number.className = "episode-number";
        number.textContent = String(index + 1).padStart(2, "0");

        const name = document.createElement("span");
        name.className = "episode-name";
        name.textContent = episode.title;

        const status = document.createElement("span");
        status.className = "episode-status";

        if (hasParts) {
            const expanded =
                expandedEpisodes.has(index) ||
                (search && matchingParts.length > 0);

            status.textContent =
                isEpisodeCompleted(index)
                    ? "✓"
                    : expanded ? "▲" : "▼";

            button.addEventListener("click", () => {
                if (expandedEpisodes.has(index)) {
                    expandedEpisodes.delete(index);
                    renderEpisodes();
                } else {
                    expandedEpisodes.add(index);
                    renderEpisodes();
                }
            });
        } else {
            status.textContent =
                completed.includes(completionId(index)) ? "✓" : "";

            button.addEventListener("click", () => {
                loadEpisode(index);
            });
        }

        button.appendChild(number);
        button.appendChild(name);
        button.appendChild(status);
        group.appendChild(button);

        /* Render Part 01, Part 02, Part 03... */
        const showParts =
            hasParts &&
            (
                expandedEpisodes.has(index) ||
                (search && matchingParts.length > 0)
            );

        if (showParts) {
            const partsContainer = document.createElement("div");
            partsContainer.className = "episode-parts";

            episode.parts.forEach((part, partIndex) => {
                if (
                    search &&
                    !episodeMatches &&
                    !part.title.toLowerCase().includes(search)
                ) {
                    return;
                }

                const partButton = document.createElement("button");
                partButton.type = "button";
                partButton.className = "episode episode-part";

                if (
                    index === currentEpisode &&
                    partIndex === currentPart
                ) {
                    partButton.classList.add("active");
                }

                const partNumber = document.createElement("span");
                partNumber.className = "episode-number";
                partNumber.textContent = "↳";

                const partName = document.createElement("span");
                partName.className = "episode-name";
                partName.textContent = part.title;

                const partStatus = document.createElement("span");
                partStatus.className = "episode-status";
                partStatus.textContent =
                    completed.includes(
                        completionId(index, partIndex)
                    )
                        ? "✓"
                        : "▶";

                partButton.addEventListener("click", event => {
                    event.stopPropagation();
                    loadPart(index, partIndex);
                });

                partButton.appendChild(partNumber);
                partButton.appendChild(partName);
                partButton.appendChild(partStatus);

                partsContainer.appendChild(partButton);
            });

            group.appendChild(partsContainer);
        }

        episodeList.appendChild(group);
    });
}

